"""Seed the deterministic prototype cohort used for the dashboard figure.

Twenty children, four in each of five districts, with a fixed seed so the
figure in the paper can be regenerated byte-for-byte by a reviewer. Signals are
left connected, so this also exercises the real registration workflow.
"""
from datetime import timedelta
import random

from django.core.management.base import BaseCommand
from django.utils import timezone

from apps.immunization.models import Caregiver, Child, VaccineSchedule
from apps.immunization.services.risk_engine import score_cohort

DISTRICTS = ["Gulu", "Mbarara", "Jinja", "Wakiso", "Kampala"]
PER_DISTRICT = 4
SEED = 20260901


class Command(BaseCommand):
    help = "Create the 20-child prototype cohort (5 districts x 4 children)."

    def add_arguments(self, parser):
        parser.add_argument("--flush", action="store_true",
                            help="delete existing caregivers and children first")

    def handle(self, *args, **options):
        if options["flush"]:
            Caregiver.objects.all().delete()

        rng = random.Random(SEED)
        today = timezone.now().date()
        created = 0
        for d, district in enumerate(DISTRICTS):
            for i in range(PER_DISTRICT):
                n = d * PER_DISTRICT + i
                caregiver = Caregiver.objects.create(
                    full_name="Caregiver %02d" % n,
                    phone_number="+2567770%05d" % n,
                    email="caregiver%02d@example.org" % n,
                    district=district,
                    village="Village %d" % (n % 7),
                    preferred_language=Caregiver.PreferredLanguage.ENGLISH,
                )
                # Ages spread across the schedule, including infants with a
                # dose due within the week, so the figure shows a cohort that
                # spans all three risk tiers rather than saturating in one.
                age = rng.choice([5, 38, 47, 66, 74, 95, 130, 200, 290, 430, 610])
                child = Child.objects.create(
                    caregiver=caregiver,
                    full_name="Child %02d" % n,
                    date_of_birth=today - timedelta(days=age),
                    gender=Child.Gender.MALE if n % 2 else Child.Gender.FEMALE,
                )

                # Heterogeneous adherence: each caregiver has a latent
                # attendance propensity, so past doses are recorded as given
                # with that probability. Without this every child is overdue
                # on every past dose and the risk tiers carry no information.
                propensity = rng.betavariate(5.0, 2.0)
                given = []
                for row in child.vaccines.filter(due_date__lt=today):
                    if rng.random() < propensity:
                        row.administered = True
                        row.administered_date = row.due_date
                        given.append(row)
                if given:
                    VaccineSchedule.objects.bulk_update(
                        given, ["administered", "administered_date"]
                    )
                created += 1

        result = score_cohort()
        self.stdout.write(self.style.SUCCESS(
            "Seeded %d children across %d districts; scored %d."
            % (created, len(DISTRICTS), result["scored"])
        ))
